export function parseSectionOrder(orderStr?: string): InvoiceSectionKey[] {
  if (!orderStr) return DEFAULT_SECTION_ORDER;
  const list = orderStr.split(',').map((s) => s.trim()) as InvoiceSectionKey[];
  const valid = list.filter((s) => DEFAULT_SECTION_ORDER.includes(s));
  
  // If 'details' was missing from an older saved order, insert it right after 'header'
  for (const s of DEFAULT_SECTION_ORDER) {
    if (!valid.includes(s)) {
      if (s === 'details') {
        const headerIdx = valid.indexOf('header');
        if (headerIdx !== -1) {
          valid.splice(headerIdx + 1, 0, 'details');
        } else {
          valid.unshift('details');
        }
      } else {
        valid.push(s);
      }
    }
  }
  return valid;
}
